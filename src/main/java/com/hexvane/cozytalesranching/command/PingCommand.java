package com.hexvane.cozytalesranching.command;

import com.hypixel.hytale.component.Ref;
import com.hypixel.hytale.component.Store;
import com.hypixel.hytale.server.core.Message;
import com.hypixel.hytale.server.core.command.system.CommandContext;
import com.hypixel.hytale.server.core.command.system.basecommands.AbstractPlayerCommand;
import com.hypixel.hytale.server.core.universe.PlayerRef;
import com.hypixel.hytale.server.core.universe.world.World;
import com.hypixel.hytale.server.core.universe.world.storage.EntityStore;
import javax.annotation.Nonnull;

public final class PingCommand extends AbstractPlayerCommand {
    public PingCommand() {
        super("ping", "cozyranch_commands.commands.cozyranch.ping.desc");
        this.setPermissionGroups("hytale:Adventurer");
    }

    @Override
    protected void execute(
        @Nonnull CommandContext context,
        @Nonnull Store<EntityStore> store,
        @Nonnull Ref<EntityStore> ref,
        @Nonnull PlayerRef playerRef,
        @Nonnull World world
    ) {
        playerRef.sendMessage(Message.translation("cozyranch_commands.commands.cozyranch.ping.success"));
    }
}
